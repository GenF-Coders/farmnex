from fastapi import APIRouter
from app.core.responses import ok
router=APIRouter()
@router.get("")
async def inventory(): return ok([{ "id":1,"crop_id":1,"available_quantity":500,"reserved_quantity":100,"unit":"kg" }])
@router.get("/{item_id}")
async def item(item_id:int): return ok({"id":item_id,"available_quantity":500,"reserved_quantity":100,"unit":"kg"})
@router.post("")
async def create_inventory(): return ok({"id":2,"created":True})
@router.patch("/{item_id}")
async def update_inventory(item_id:int): return ok({"id":item_id,"updated":True})
@router.post("/{item_id}/reserve")
async def reserve(item_id:int): return ok({"id":item_id,"reserved":50,"available":450})
@router.post("/{item_id}/release")
async def release(item_id:int): return ok({"id":item_id,"released":50})
@router.post("/{item_id}/adjust")
async def adjust(item_id:int): return ok({"id":item_id,"adjusted":True})
