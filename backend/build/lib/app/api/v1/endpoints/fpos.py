from fastapi import APIRouter
from app.core.responses import ok
router = APIRouter()
@router.get("")
async def fpos(): return ok([{ "id": 301, "name": "Pune Agro FPO", "district": "Pune", "members": 128, "verified": True }])
@router.post("")
async def create_fpo(): return ok({"id": 302, "status": "pending_verification"}, "FPO created")
@router.get("/{fpo_id}")
async def fpo(fpo_id: int): return ok({"id": fpo_id, "name": "Pune Agro FPO", "members": 128, "verified": True})
@router.patch("/{fpo_id}")
async def update_fpo(fpo_id: int): return ok({"id": fpo_id, "updated": True})
@router.get("/{fpo_id}/members")
async def members(fpo_id: int): return ok([{ "user_id": 1001, "name": "Ramesh Patil", "role": "FARMER" }])
@router.post("/{fpo_id}/members")
async def add_member(fpo_id: int): return ok({"fpo_id": fpo_id, "user_id": 1002, "added": True})
@router.delete("/{fpo_id}/members/{user_id}")
async def remove_member(fpo_id: int, user_id: int): return ok({"fpo_id": fpo_id, "user_id": user_id, "removed": True})
@router.get("/{fpo_id}/crops")
async def fpo_crops(fpo_id: int): return ok([{ "crop_id": 1, "crop_name": "Tomato", "quantity": 2500, "unit": "kg" }])
